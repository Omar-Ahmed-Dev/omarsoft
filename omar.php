عايز اعرف اكتر عن  وضع شرط في كويري عرض البيانات في لارافيل 
في Laravel، يمكنك وضع شروط في استعلامات عرض البيانات باستخدام Eloquent ORM أو Query Builder. هذا يسمح لك بتصفية البيانات بناءً على معايير محددة قبل عرضها للمستخدمين. إليك كيفية القيام بذلك باستخدام كلا الطريقتين:
عايز اعرف  التلخيص التعريف عنهم 
1. Eloquent ORM:
Eloquent هو نظام ORM (Object-Relational Mapping) المدمج في Laravel، والذي يسمح لك بالتفاعل مع قاعدة البيانات باستخدام نماذج PHP بدلاً من كتابة استعلامات SQL مباشرة. يمكنك وضع شروط في استعلامات Eloquent باستخدام طرق مثل where()، orWhere()، وwhereIn().
مثال:
```php
$users = User::where('status', 'active')
             ->where('age', '>', 18)
             ->get();
```في هذا المثال، يتم جلب جميع المستخدمين الذين لديهم حالة "active" وعمر أكبر من 18.
2. Query Builder:
Query Builder هو أداة قوية في Laravel تتيح لك بناء استعلامات SQL بطريقة برمجية. يمكنك أيضًا وضع شروط باستخدام طرق مشابهة لتلك المستخدمة في Eloquent.
مثال:   
```php
$users = DB::table('users')
            ->where('status', 'active')
            ->where('age', '>', 18)
            ->get();
```في هذا المثال، يتم جلب جميع المستخدمين من جدول "users" الذين لديهم حالة "active" وعمر أكبر من 18.
باستخدام كلا الطريقتين، يمكنك بسهولة إضافة شروط لتصفية البيانات التي تريد عرضها بناءً على معايير محددة، مما يجعل تطبيقك أكثر ديناميكية ومرونة.
