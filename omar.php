الباجنيشن (Pagination) هو تقنية تُستخدم في تطوير الويب لتقسيم المحتوى الكبير إلى صفحات أصغر، مما يسهل على المستخدمين تصفح البيانات بدلاً من تحميل كل البيانات مرة واحدة. هذا يكون مفيدًا بشكل خاص عند التعامل مع مجموعات كبيرة من البيانات، مثل قوائم المنتجات، المقالات، أو أي نوع آخر من المحتوى الذي يمكن أن يكون طويلاً جدًا.
وظيفة الباجنيشن هي تحسين تجربة المستخدم من خلال تقليل وقت التحميل وتحسين الأداء، بالإضافة إلى تسهيل التنقل بين أجزاء المحتوى المختلفة. بدلاً من عرض جميع العناصر في صفحة واحدة، يتم تقسيمها إلى صفحات متعددة، ويمكن للمستخدمين التنقل بين هذه الصفحات باستخدام روابط أو أزرار مخصصة.
في PHP و MySQL، يتم تنفيذ الباجنيشن عادةً عن طريق تحديد عدد العناصر التي سيتم عرضها في كل صفحة، ثم استخدام استعلامات SQL مع عبارات LIMIT و OFFSET لجلب البيانات المناسبة لكل صفحة بناءً على رقم الصفحة الحالي.
على سبيل المثال، إذا كنت تعرض 10 عناصر في كل صفحة، وعرضت الصفحة الأولى، فسيتم جلب العناصر من 0 إلى 9. إذا انتقلت إلى الصفحة الثانية، فسيتم جلب العناصر من 10 إلى 19، وهكذا.
